// Writes shared/claim-chain-vectors.json: the reference vectors for the reclaim hash chain
// (docs/architecture.md §5.4). Node computes them here; the Dart, TypeScript and Firestore-rules
// suites each verify them independently. Nobody is trusted to agree by assumption.
//   node scripts/gen-claim-vectors.mjs          write the file
//   node scripts/gen-claim-vectors.mjs --check  exit 1 if the file differs from what this script produces
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OUT = fileURLToPath(new URL('../shared/claim-chain-vectors.json', import.meta.url));

const ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
const CODE_LENGTH = 20;
const CHAIN_LENGTH = 1000;

const sha256Hex = (input) => createHash('sha256').update(input).digest('hex');

/** Reference canonicalisation. Returns null for invalid input. */
function canonicalise(input) {
  const s = input
    .toUpperCase()
    .replace(/[\s-]/g, '')
    .replace(/O/g, '0')
    .replace(/[IL]/g, '1');
  if (s.length !== CODE_LENGTH) return null;
  for (const ch of s) if (!ALPHABET.includes(ch)) return null;
  return s;
}

const display = (canonical) => canonical.match(/.{5}/g).join('-');

/** links[i] = Hⁱ (1-based; links[0] unused). */
function chain(canonical, step = (prev) => sha256Hex(Buffer.from(prev, 'utf8'))) {
  const links = [null, sha256Hex(Buffer.from(canonical, 'utf8'))];
  for (let i = 2; i <= CHAIN_LENGTH; i++) links.push(step(links[i - 1]));
  return links;
}

// Deliberately wrong implementations. Their H⁹⁹⁹ must NOT satisfy the rules for the correct H¹⁰⁰⁰.
function misencodings(canonical) {
  const rawBytes = chain(canonical, (prev) => sha256Hex(Buffer.from(prev, 'hex')));
  const upperStep = chain(canonical, (prev) => sha256Hex(Buffer.from(prev.toUpperCase(), 'utf8')));
  const fromDisplay = (() => {
    const links = [null, sha256Hex(Buffer.from(display(canonical), 'utf8'))];
    for (let i = 2; i <= CHAIN_LENGTH; i++) links.push(sha256Hex(Buffer.from(links[i - 1], 'utf8')));
    return links;
  })();
  const base64Step = chain(canonical, (prev) =>
    createHash('sha256').update(Buffer.from(prev, 'utf8')).digest('base64'),
  );
  return [
    { kind: 'raw-bytes', note: 'Hashes the 32 raw digest bytes instead of the 64-char hex string', h999: rawBytes[999] },
    { kind: 'uppercase-step', note: 'Hashes the UPPERCASE hex string at each step', h999: upperStep[999] },
    { kind: 'display-form-seed', note: 'Hashes the hyphenated display code for H¹', h999: fromDisplay[999] },
    { kind: 'base64-digest', note: 'Encodes digests as base64 instead of hex', h999: base64Step[999] },
  ];
}

const SEEDS = [
  {
    name: 'realistic',
    canonical: '7K3QM2XPA9HD4RT8VW1N',
    inputVariants: ['7K3QM-2XPA9-HD4RT-8VW1N', '7k3qm-2xpa9-hd4rt-8vw1n', ' 7K3QM 2XPA9 HD4RT 8VW1N '],
  },
  {
    name: 'all-zero',
    canonical: '00000000000000000000',
    inputVariants: ['OOOOO-ooooo-00000-00000', '00000000000000000000'],
  },
  {
    name: 'ambiguous-characters',
    canonical: 'A1B0C1D0E1F0G1H0J1K0',
    inputVariants: ['AIBOC-LDOEI-FOGIH-OJIKO', 'a1b0c-1d0e1-f0g1h-0j1k0', 'aib0c ld0ei f0gih 0jik0'],
  },
];

const INVALID_INPUTS = [
  { input: '', reason: 'empty' },
  { input: '7K3QM-2XPA9-HD4RT-8VW1', reason: '19 characters' },
  { input: '7K3QM-2XPA9-HD4RT-8VW1NN', reason: '21 characters' },
  { input: '7K3QM-2XPA9-HD4RT-8VW1U', reason: 'U is not in the Crockford alphabet' },
  { input: '7K3QM-2XPA9-HD4RT-8VW1#', reason: 'symbol' },
  { input: '7K3QM_2XPA9_HD4RT_8VW1N', reason: 'underscore separators' },
];

function build() {
  const cases = SEEDS.map(({ name, canonical, inputVariants }) => {
    for (const v of inputVariants) {
      if (canonicalise(v) !== canonical) throw new Error(`Variant "${v}" does not canonicalise to ${canonical}`);
    }
    const links = chain(canonical);
    const pick = [1, 2, 3, 997, 998, 999, 1000];
    return {
      name,
      displayCode: display(canonical),
      canonical,
      inputVariants,
      links: Object.fromEntries(pick.map((i) => [`h${i}`, links[i]])),
      misencoded: misencodings(canonical),
    };
  });

  for (const { input } of INVALID_INPUTS) {
    if (canonicalise(input) !== null) throw new Error(`Invalid input "${input}" was accepted`);
  }

  return {
    $comment:
      'GENERATED by scripts/gen-claim-vectors.mjs. Spec: docs/architecture.md §5.4. ' +
      'Every implementation (Dart, TypeScript, Firestore rules) must reproduce these values exactly.',
    spec: {
      alphabet: ALPHABET,
      codeLength: CODE_LENGTH,
      displayGroups: '5-5-5-5 joined by "-"',
      canonicalise: 'uppercase; strip spaces and hyphens; O→0, I→1, L→1; reject anything outside the alphabet; length must be 20',
      h1: 'lowercase hex of SHA-256 over UTF-8 bytes of the 20-char canonical code',
      hNext: 'lowercase hex of SHA-256 over UTF-8 bytes of the previous 64-char lowercase hex link',
      chainLength: CHAIN_LENGTH,
      storedOnCreate: 'h1000',
      reclaimReveals: 'the link one step before the stored claimHash',
    },
    cases,
    invalidInputs: INVALID_INPUTS,
  };
}

const content = JSON.stringify(build(), null, 2) + '\n';

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (current !== content) {
    console.error('Stale: shared/claim-chain-vectors.json. Run `node scripts/gen-claim-vectors.mjs`.');
    process.exit(1);
  }
  console.log('Claim-chain vectors are up to date.');
} else {
  writeFileSync(OUT, content);
  console.log('wrote shared/claim-chain-vectors.json');
}
